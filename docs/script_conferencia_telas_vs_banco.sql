estado AS MATERIALIZED (
  SELECT u.tipo, u.nome,
         CASE u.tipo
           WHEN 'funcao' THEN EXISTS (SELECT 1 FROM pg_proc p
                                       JOIN pg_namespace n ON n.oid = p.pronamespace
                                      WHERE n.nspname = 'public' AND p.proname = u.nome)
           WHEN 'tabela' THEN to_regclass('public.' || u.nome) IS NOT NULL
         END AS existe
  FROM usado u
)
SELECT 1 AS ordem,
       'FALTA'::text                                  AS situacao,
       tipo                                           AS tipo,
       nome                                           AS peca,
       CASE
         WHEN nome LIKE 'ponto%'      THEN 'Ponto'
         WHEN nome LIKE 'epi%'        THEN 'EPI'
         WHEN nome LIKE 'folha%'      THEN 'Folha'
         WHEN nome LIKE 'ferias%'     THEN 'Ferias'
         WHEN nome LIKE 'psicossocial%' THEN 'Psicossocial'
         WHEN nome LIKE 'afastament%' THEN 'Afastamentos'
         WHEN nome LIKE 'admiss%'     THEN 'Admissoes'
         WHEN nome LIKE 'beneficio%'  THEN 'Beneficios'
         WHEN nome LIKE 'ergonomia%'  THEN 'Ergonomia'
         WHEN nome LIKE 'hub%'        THEN 'Hub contabil'
         WHEN nome LIKE 'trilha%' OR nome LIKE 'academia%' THEN 'Treinamentos'
         WHEN nome LIKE 'qa%'         THEN 'Bancada de QA'
         ELSE 'Outros'
       END                                            AS modulo
FROM estado WHERE NOT existe
UNION ALL
SELECT 0, 'RESUMO',
       (SELECT count(*) FROM estado WHERE existe)::text || ' de '
         || (SELECT count(*) FROM estado)::text || ' pecas presentes',
       (SELECT count(*) FROM estado WHERE NOT existe)::text || ' faltando',
       CASE WHEN (SELECT count(*) FROM estado WHERE NOT existe) = 0
            THEN 'OK — as telas tem lastro neste banco'
            ELSE 'CONFERIR — as pecas listadas abaixo nao existem aqui' END
ORDER BY ordem, modulo, tipo, peca;
