-- ============================================================================
-- CONFERENCIA: as telas tem lastro no banco de PRODUCAO?
--
-- POR QUE ESTE ARQUIVO
-- As telas de teste, de homologacao e de producao sao construidas do MESMO
-- codigo; o que muda entre elas e so a qual banco apontam. Ja o BANCO de cada
-- ambiente e diferente: no de teste as migrations chegam sozinhas, e no de
-- producao so chega o que e entregue a mao. Entao uma tela pode existir e o
-- banco de producao nao ter a peca que ela chama — a tela publica e quebra no
-- uso.
--
-- O QUE ELE FAZ
-- Le do proprio codigo das telas os nomes que elas chamam — 65 funcoes e
-- 190 tabelas/visoes — e confere um a um se existem NESTE banco.
--
-- COMO LER
--   * lista vazia (so a linha RESUMO com OK): todas as telas tem lastro;
--   * linhas FALTA: sao exatamente as pecas ausentes. Cada uma corresponde a
--     uma tela que vai falhar no uso. A coluna modulo ajuda a ver o tamanho do
--     estrago por area.
--
-- O QUE ELE NAO ALCANCA
-- Chamada montada dinamicamente no codigo (nome em variavel) nao aparece aqui,
-- nem coluna que falta numa tabela que existe. Ausencia de linha FALTA nao e
-- garantia absoluta de que nada quebra — e a eliminacao da causa mais comum.
-- Os depositos de arquivo (storage) tambem ficam de fora: sao outro subsistema.
--
-- SOMENTE LEITURA. Nao cria, nao altera e nao apaga nada.
-- ============================================================================

